'use strict';
// Tests for ui-spec-render.cjs (objective 34-05 — the four derived artifacts).
//
// `renderSurfaceSpec(spec)` is PURE: it takes a parsed Surface Spec front matter and returns
// `{manifest, navGraphMermaid, controlTableMd, captureList}`. No file I/O lives in the library,
// which is what makes D1 (determinism) and D2 (the committed snapshots) cheap to assert.
//
// Hand-written fixtures only (CLAUDE.md habit 4 / fixture_strategy: generators). Every case is
// either the ONE positive control — `__fixtures__/ui-spec/projects-rail.md`, hand-transcribed
// from proposal §4.2 in 34-02 — or a `mutate()` of it. Nothing is generated by a model.
//
// CASE M1 IS THE LOAD-BEARING ONE. It writes the generated manifest to a temp file and hands it
// to `flutter-ui-eval.cjs`'s REAL `loadManifest()`. Asserting the manifest's shape from reading
// that file's source would prove this test author's memory of it; executing the consumer proves
// the shape. `flutter-ui-eval.cjs` is READ here and never modified — W2 owns its judge
// behaviour and `references[]` calibration, and the objective's out-of-scope list says so.
//
// RED (task 1): this require fails until ui-spec-render.cjs is created.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const { parseSurfaceSpec } = require('./ui-spec.cjs');
const { loadManifest } = require('./flutter-ui-eval.cjs'); // the REAL consumer — not a copy of it
const {
  renderSurfaceSpec,
  DEFAULT_IDENTITY,
  DEFAULT_THEME,
  DEFAULT_WIDTH
} = require('./ui-spec-render.cjs');

const FIXTURE_DIR = path.join(__dirname, '__fixtures__', 'ui-spec');
const POSITIVE_CONTROL = path.join(FIXTURE_DIR, 'projects-rail.md');

const TMP_DIRS = [];

// ─── The spec factory (the same one 34-03/34-04 use — one authoring rule per objective) ──────

/** The parsed front matter of the positive control — a fresh object per call. */
function loadPositiveControl() {
  return parseSurfaceSpec(fs.readFileSync(POSITIVE_CONTROL, 'utf-8'), { source: POSITIVE_CONTROL })
    .frontMatter;
}

/** A deep-cloned copy of `spec` with `fn` applied. `structuredClone` is a node builtin. */
function mutate(spec, fn) {
  const copy = structuredClone(spec);
  fn(copy);
  return copy;
}

function tmpDir(prefix) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  TMP_DIRS.push(dir);
  return dir;
}

test.after(() => {
  for (const d of TMP_DIRS) {
    try { fs.rmSync(d, { recursive: true, force: true }); } catch { /* best effort */ }
  }
});

// ─── M1: the generated manifest, proven against the engine that consumes it ──────────────────

test('Case M1 — the generated manifest loads through the REAL flutter-ui-eval loadManifest()', () => {
  const { manifest } = renderSurfaceSpec(loadPositiveControl());

  const dir = tmpDir('ui-spec-render-m1-');
  const file = path.join(dir, 'generated.manifest.json');
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2), 'utf-8');

  // The only proof that matters: the consumer executes without throwing. loadManifest() enforces
  // three structural requirements (valid JSON, a JSON object, a `states` array) and names which
  // one failed in its message — see flutter-ui-eval.cjs:57.
  const parsed = loadManifest(file);

  assert.ok(Array.isArray(parsed.states), 'loadManifest returned a manifest with no states array');
  assert.strictEqual(parsed.states.length, 8, 'the positive control declares eight states');
});

// ─── M2: all five plan-named keys, on every state, null/[] rather than absent ────────────────

test('Case M2 — every state carries state_id, seed, as, fault and references (all five, always)', () => {
  const { manifest } = renderSurfaceSpec(loadPositiveControl());

  const REQUIRED = ['state_id', 'seed', 'as', 'fault', 'references'];
  for (const st of manifest.states) {
    for (const key of REQUIRED) {
      assert.ok(
        Object.prototype.hasOwnProperty.call(st, key),
        `state ${st.state_id} is missing the key \`${key}\` — a consumer must never have to tell "absent" from "empty"`
      );
    }
    assert.ok(Array.isArray(st.references), `state ${st.state_id}: references must be an array`);
  }

  const byId = new Map(manifest.states.map((s) => [s.state_id, s]));

  // `as` defaults to the primary identity (§7.4: "an identity set per app (primary, …)";
  // §4.2: "identity from the e2e identity set; default: primary user").
  assert.strictEqual(byId.get('populated').as, 'workspace-member', 'a declared `as` is carried through');
  assert.strictEqual(byId.get('empty').as, DEFAULT_IDENTITY, '`as` defaults to the primary identity');
  assert.strictEqual(DEFAULT_IDENTITY, 'primary');

  // `fault` is null — NOT absent — when the state declares none.
  assert.strictEqual(byId.get('error').fault, 'projects-list-500');
  assert.strictEqual(byId.get('populated').fault, null, '`fault` is null, not absent, when undeclared');

  // `seed` likewise: every state in the positive control declares one (invariant STATE001), so
  // the null path is proven by removing one rather than by hoping a spec omits it.
  const seedless = renderSurfaceSpec(
    mutate(loadPositiveControl(), (s) => { delete s.states[0].seed; }),
    { validate: false } // STATE001 would refuse this spec; the key convention is what is under test
  ).manifest;
  assert.strictEqual(seedless.states[0].seed, null, '`seed` is null, not absent, when undeclared');
});

// ─── M3: states[] order is the spec's order, exactly ─────────────────────────────────────────

test('Case M3 — manifest.states order equals the spec states order exactly', () => {
  const spec = loadPositiveControl();
  const { manifest } = renderSurfaceSpec(spec);

  assert.deepStrictEqual(
    manifest.states.map((s) => s.state_id),
    spec.states.map((s) => s.id),
    'the sheet rows and the probe capture order both inherit this ordering'
  );
});

// ─── M4: the honest-output header ────────────────────────────────────────────────────────────

test('Case M4 — the manifest carries surface, engine_version and schema_version', () => {
  const { manifest } = renderSurfaceSpec(loadPositiveControl());

  assert.strictEqual(manifest.surface, 'projects-rail');
  assert.strictEqual(typeof manifest.engine_version, 'string');
  assert.ok(manifest.engine_version.length > 0, 'engine_version must be a non-empty string');
  assert.strictEqual(manifest.schema_version, 1);
});

// ─── M5: references[], and the never-drop rule ───────────────────────────────────────────────

test('Case M5 — a `ref` becomes references[0]; a state with no `ref` gets [] and is NOT dropped', () => {
  const spec = loadPositiveControl();
  const { manifest } = renderSurfaceSpec(spec);
  const byId = new Map(manifest.states.map((s) => [s.state_id, s]));

  assert.deepStrictEqual(byId.get('populated').references, ['locked/populated.png']);

  // Every other state in the positive control declares no `ref`. All seven are still here —
  // dropping one is how a gate stops seeing the thing it was built to see (34-06 renders them
  // MISSING instead).
  const refless = spec.states.filter((s) => s.ref === undefined).map((s) => s.id);
  assert.strictEqual(refless.length, 7, 'the positive control has seven states with no ref');
  for (const id of refless) {
    assert.ok(byId.has(id), `state ${id} was dropped from the manifest`);
    assert.deepStrictEqual(byId.get(id).references, [], `state ${id}: references must be [], not absent`);
  }

  // The defaults the capture list and 34-06's grid columns are built from, pinned here so a
  // change to either constant fails a named case rather than drifting silently.
  assert.strictEqual(DEFAULT_THEME, 'light');
  assert.strictEqual(DEFAULT_WIDTH, 1280);
});
